"""Политика одноразовых ссылок входа («magic link») — чистые правила.

Токен наружу уходит только в письме; на сервере хранится ЕГО ХЭШ. Разница
существенная: дамп/утечка снапшота Redis с сырыми токенами дала бы вход в
чужие аккаунты на всё время жизни записей, а из sha256 токен не восстановить.
Соль не нужна — токен уже 32 байта криптостойкой энтропии, перебор словарём
невозможен.
"""

from __future__ import annotations

import hashlib
import secrets

MAGIC_LINK_TTL_MINUTES = 15
"""Сколько живёт ссылка входа.

Компромисс: письмо должно пережить задержки доставки и переключение с
телефона на компьютер, но чем дольше живёт ссылка, тем дольше её можно
использовать из чужого почтового ящика (доступ к почте = доступ к аккаунту).
15 минут — обычная практика для входа по ссылке.
"""

MAGIC_LINK_TTL_SECONDS = MAGIC_LINK_TTL_MINUTES * 60

MAX_LETTERS_PER_EMAIL = 5
"""Сколько писем со ссылкой можно отправить на ОДИН адрес за окно.

Это защита чужого ящика от бомбардировки: общий лимит ``/auth`` считается по
IP и не мешает разослать сотни писем на один адрес с разных IP. Превышение не
меняет ответ (всё те же 202 — иначе по коду ответа различались бы
существующие адреса), просто письмо не уходит.
"""

LETTERS_WINDOW_SECONDS = 3600
"""Окно лимита писем на адрес — час."""


def generate_magic_link_token() -> str:
    """Одноразовый секрет ссылки: 32 байта энтропии в base64url."""
    return secrets.token_urlsafe(32)


def hash_magic_link_token(token: str) -> str:
    """sha256-хэш токена — то, что реально хранится на сервере."""
    return hashlib.sha256(token.encode("utf-8")).hexdigest()


def email_quota_key(email: str) -> str:
    """Ключ счётчика писем — sha256 адреса вместо самого адреса.

    Это НЕ псевдонимизация в смысле 152-ФЗ: несолёный хэш адреса обратим
    перебором (пространство почтовых адресов мало), да и сам адрес всё равно
    лежит в Redis открытым те 15 минут, пока жива ссылка. Смысл скромнее —
    не превращать дамп ключей Redis в готовый к чтению список «кто пытался
    войти за последний час»: ключи видны любому, кто может сделать ``KEYS``,
    тогда как значения ссылок надо запрашивать поимённо. Считаться от хэша
    ничем не дороже, поэтому берём то, что дёшево.
    """
    return hashlib.sha256(email.encode("utf-8")).hexdigest()
